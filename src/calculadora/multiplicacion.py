class Multiplicacion: 
    def __init__(self):
        pass

    def multiplicar(self, a: int, b: int) -> int:
        """
        Multiplica dos numeros

        Args:
            a (int): Primer numero
            b (int): Segundo numero
        
        Return: 
            Retorna la multiplicacion entre a y b
        """
        
        return a*b
